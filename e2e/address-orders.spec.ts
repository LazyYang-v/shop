import { expect, test } from '@playwright/test'

test('new buyer creates and chooses an address then lands in my orders', async ({ page }) => {
  const email = `address-orders-${Date.now()}@example.com`
  await page.goto('/')
  await page.getByRole('button', { name: '免费注册' }).click()
  let dialog = page.getByRole('dialog')
  await dialog.locator('input[name=email]').fill(email)
  await dialog.locator('input[name=password]').fill('demo-only-password-123')
  await dialog.locator('form button[type=submit]').click()
  await expect(page.getByText('注册成功，请登录。')).toBeVisible()
  dialog = page.getByRole('dialog')
  await dialog.locator('input[name=email]').fill(email)
  await dialog.locator('input[name=password]').fill('demo-only-password-123')
  await dialog.locator('form button[type=submit]').click()
  await page.getByRole('button', { name: '🛒 购物车 查看' }).click()
  await page.getByRole('button', { name: '加入购物车' }).first().click()
  await page.getByRole('button', { name: '结算', exact: true }).click()
  await expect(page.getByRole('heading', { name: '确认订单', exact: true })).toBeVisible()
  for (const [label, value] of Object.entries({ '收货人': '演示买家', '手机号码': '13800138000', '省份': '浙江省', '城市': '杭州市', '区县': '西湖区', '详细地址': '演示路 8 号' })) await page.getByLabel(label, { exact: true }).fill(value)
  await page.getByRole('button', { name: '保存地址', exact: true }).click()
  await expect(page.getByRole('radio', { name: /演示路 8 号/ })).toBeChecked()
  await page.getByRole('button', { name: '新增收货地址' }).click()
  for (const [label, value] of Object.entries({ '收货人': '第二收件人', '手机号码': '13800138001', '省份': '上海市', '城市': '上海市', '区县': '徐汇区', '详细地址': '第二地址 9 号' })) await page.getByLabel(label, { exact: true }).fill(value)
  await page.getByRole('button', { name: '保存地址', exact: true }).click()
  await expect(page.getByRole('radio', { name: /第二地址 9 号/ })).toBeChecked()
  await page.getByRole('radio', { name: /演示路 8 号/ }).check()
  await expect(page.getByRole('radio', { name: /演示路 8 号/ })).toBeChecked()
  await page.getByRole('button', { name: '提交订单并扣减库存' }).click()
  await expect(page).toHaveURL(/view=orders.*order=/)
  await expect(page.getByRole('heading', { name: '我的订单', exact: true })).toBeVisible()
  await expect(page.getByText(/演示路 8 号/)).toBeVisible()
  await page.reload()
  await expect(page.getByText(/演示路 8 号/)).toBeVisible()
  await page.getByRole('link', { name: '返回订单列表' }).click()
  await expect(page.getByRole('link', { name: '查看详情' }).first()).toBeVisible()
  await page.getByRole('link', { name: '查看详情' }).first().click()
  await page.getByRole('link', { name: '查看物流', exact: true }).click()
  await expect(page.getByRole('heading', { name: '物流详情', exact: true })).toBeVisible()
  await expect(page.getByText('商品尚未发货，暂无运单及物流记录。')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: '物流详情', exact: true })).toBeVisible()
  await page.getByRole('link', { name: '← 返回订单详情' }).click()
  await page.getByRole('button', { name: /取消订单/ }).click()
  await expect(page.getByText('已关闭', { exact: true }).first()).toBeVisible()
})
