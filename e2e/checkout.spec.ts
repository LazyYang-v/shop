import { expect, test } from '@playwright/test'

const password = process.env.SHOP_E2E_BUYER_PASSWORD ?? 'demo-only-password-123'

test('new buyer adds an address, checks out into my orders, and refreshes after payment', async ({ page }) => {
  const email = `checkout-no-address-${Date.now()}@example.com`
  await page.goto('/')
  await page.getByRole('button', { name: '免费注册' }).click()
  let dialog = page.getByRole('dialog')
  await dialog.locator('input[name=email]').fill(email)
  await dialog.locator('input[name=password]').fill(password)
  await dialog.locator('form button[type=submit]').click()
  await expect(page.getByText('注册成功，请登录。')).toBeVisible()
  dialog = page.getByRole('dialog')
  await dialog.locator('input[name=email]').fill(email)
  await dialog.locator('input[name=password]').fill(password)
  await dialog.locator('form button[type=submit]').click()
  await expect(page.getByText(email).first()).toBeVisible()
  await page.getByRole('button', { name: '🛒 购物车 查看' }).click()
  await page.getByRole('button', { name: '加入购物车' }).first().click()
  const quantity = page.getByRole('spinbutton', { name: '春日轻盈针织开衫数量' })
  await quantity.fill('2')
  await quantity.press('Tab')
  await expect(quantity).toHaveValue('2')
  const selected = page.getByRole('checkbox', { name: '勾选春日轻盈针织开衫' })
  await selected.uncheck()
  await expect(page.locator('.commerce-summary .summary-total')).toContainText('¥0.00')
  await selected.check()
  await page.getByRole('button', { name: '结算 (2)' }).click()
  await expect(page.getByRole('heading', { name: '确认订单', exact: true })).toBeVisible()
  await expect(page.getByText('还没有收货地址，请填写下方信息。')).toBeVisible()
  await expect(page.getByRole('radio')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '新增收货地址', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '提交订单并扣减库存' })).toBeDisabled()
  for (const [label, value] of Object.entries({ '收货人': '结算演示买家', '手机号码': '13800138000', '省份': '浙江省', '城市': '杭州市', '区县': '西湖区', '详细地址': '结算演示路 8 号' })) {
    await page.getByLabel(label, { exact: true }).fill(value)
  }
  await page.getByRole('button', { name: '保存地址', exact: true }).click()
  await expect(page.getByRole('radio', { name: /结算演示路 8 号/ })).toBeChecked()
  await expect(page.getByRole('button', { name: '提交订单并扣减库存' })).toBeEnabled()

  let orderId: string | undefined
  try {
    const created = page.waitForResponse(response => response.url().endsWith('/api/orders') && response.request().method() === 'POST')
    await page.getByRole('button', { name: '提交订单并扣减库存' }).click()
    const response = await created
    expect(response.ok()).toBeTruthy()
    orderId = (await response.json()).id
    expect(orderId).toBeTruthy()
    await expect(page).toHaveURL(`/?view=orders&order=${orderId}`)
    await expect(page.getByRole('heading', { name: '我的订单', exact: true })).toBeVisible()
    await expect(page.getByRole('heading', { name: '订单详情', exact: true })).toBeVisible()
    await expect(page.locator('.orders-id')).toHaveText(orderId!)
    await expect(page.locator('.orders-status')).toHaveText('待支付')
    await expect(page.locator('.orders-total')).toContainText('¥258.00')
    await expect(page.getByText(/结算演示路 8 号/)).toBeVisible()
    await page.getByRole('button', { name: '模拟支付', exact: true }).click()
    await expect(page.getByRole('status')).toContainText('模拟支付成功')
    await expect(page.locator('.orders-status')).toHaveText('待发货')
    await page.reload()
    await expect(page.locator('.orders-id')).toHaveText(orderId!)
    await expect(page.locator('.orders-status')).toHaveText('待发货')
    await page.getByRole('link', { name: '查看物流', exact: true }).click()
    await expect(page).toHaveURL(`/?view=orders&order=${orderId}&logistics=1`)
    await expect(page.getByRole('heading', { name: '物流详情', exact: true })).toBeVisible()
    await expect(page.getByText('商品尚未发货，暂无运单及物流记录。')).toBeVisible()
    await expect(page.getByText('结算演示买家 · 138****8000')).toBeVisible()
    await page.getByRole('link', { name: '← 返回订单详情' }).click()
    await expect(page.locator('.orders-id')).toHaveText(orderId!)
    await expect(page.locator('.orders-status')).toHaveText('待发货')
  } finally {
    // Keep the paid demo order; release inventory if an earlier assertion failed.
    if (orderId) {
      const response = await page.request.get(`/api/orders/${orderId}`)
      expect(response.ok()).toBeTruthy()
      if ((await response.json()).status === 'pending_payment') {
        const csrf = await page.request.get('/api/auth/csrf')
        expect(csrf.ok()).toBeTruthy()
        const { csrf_token } = await csrf.json()
        const cancelled = await page.request.post(`/api/orders/${orderId}/cancel`, {
          headers: { 'X-CSRF-Token': csrf_token, Origin: new URL(page.url()).origin },
        })
        expect(cancelled.ok()).toBeTruthy()
        expect((await cancelled.json()).status).toBe('closed')
      }
    }
  }
})

